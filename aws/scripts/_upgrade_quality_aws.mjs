function writeQuestions(name, arr) {
  const free = arr.filter((q) => q.id <= 10).every((q) => q.isPremium === false);
  const pro = arr.filter((q) => q.id >= 11).every((q) => q.isPremium === true);
  if (!free || !pro) throw new Error(`${name} premium flags`);
  if (arr.length !== 30) throw new Error(`${name} count ${arr.length}`);
  const lens = arr.map((q) => q.explicacao_profunda.length);
  const min = Math.min(...lens);
  const avg = Math.round(lens.reduce((a, b) => a + b, 0) / lens.length);
  if (min < 220) throw new Error(`${name} min expl ${min}`);
  fs.writeFileSync(
    path.join(PARTS, `part-aws-${name}-questions.json`),
    JSON.stringify(arr, null, 2) + "\n",
    "utf8"
  );
  console.log(`questions ${name}: min=${min} avg=${avg} n=${arr.length}`);
}

