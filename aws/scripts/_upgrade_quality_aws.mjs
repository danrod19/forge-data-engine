function Q(id, premium, enunciado, alts, rc, expl, part) {
  if (alts.length !== 4) throw new Error(`id ${id} alts`);
  if (rc < 0 || rc > 3) throw new Error(`id ${id} rc`);
  // Ensure ≥220 with scenario tip if author draft was short
  if (expl.length < 220) {
    expl =
      expl.trim() +
      " No cenário SAA, amarre a escolha ao requisito (segurança, path de rede ou custo) e descarte distractors que misturam domínios sem evidência no enunciado.";
  }
  if (expl.length < 220) throw new Error(`id ${id} expl ${expl.length}: ${expl.slice(0, 60)}`);
  if (/^A resposta correta é/i.test(expl)) throw new Error(`id ${id} bad start`);
  return {
    id,
    question_type: "traditional",
    isPremium: premium,
    enunciado,
    alternativas: alts,
    resposta_correta: rc,
    explicacao_profunda: expl,
    part_id: part,
  };
}

